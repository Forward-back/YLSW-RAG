"""提示词注入防护：用户输入转义 + 拒答话术。

标签隔离的有效性依赖用户输入无法伪造标签闭合：
半角尖括号换全角后，注入者写不出真实的 </user_question> 等标签。
"""


def escape_user_input(text: str) -> str:
    """用户输入转义：半角尖括号换全角，防注入伪造标签闭合。"""
    return text.replace("<", "＜").replace(">", "＞")


